#!/usr/bin/env node
// Prebuild step. Bundles the browser editor's client (src/edit/editor/client/
// main.ts) for the browser and emits src/edit/editor/client.generated.ts with
// the bundle and its stylesheet as TS string constants, which the editor
// server (`dailies cut edit`) serves. Both tsx (dev) and the CLI's esbuild
// bundle consume them as plain imports — no loaders, no runtime fs reads.
//
//   EDITOR_CLIENT_JS   esbuild iife bundle of client/main.ts
//   EDITOR_CLIENT_CSS  client/style.css, verbatim
//
// The bundle targets the browser, so a client import that reaches Node (fs,
// child_process, the logger) fails the build here rather than in the page.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const editorDir = resolve(root, "src/edit/editor");

const bundle = await build({
  entryPoints: [resolve(editorDir, "client/main.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  write: false,
  logLevel: "warning",
});
const js = bundle.outputFiles[0]?.text;
if (!js) {
  process.stderr.write("embed-editor: esbuild produced no bundle\n");
  process.exit(1);
}
const css = readFileSync(resolve(editorDir, "client/style.css"), "utf8");

const content = [
  "// AUTO-GENERATED by scripts/embed-editor.mjs. DO NOT EDIT.",
  "// Sources: src/edit/editor/client/. Regenerate with `pnpm --filter dailies-cli prebuild`.",
  "",
  `export const EDITOR_CLIENT_JS: string = ${JSON.stringify(js)};`,
  `export const EDITOR_CLIENT_CSS: string = ${JSON.stringify(css)};`,
  "",
].join("\n");

// Compare before writing, so an unchanged client doesn't touch the file and
// invalidate everything downstream of its mtime.
const out = resolve(editorDir, "client.generated.ts");
if (!existsSync(out) || readFileSync(out, "utf8") !== content) {
  writeFileSync(out, content);
}
